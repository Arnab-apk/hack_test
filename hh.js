function calculateSum(a, b) {
    /**
     * Calculates and returns the sum of two numbers.
     * This mirrors the functionality in hello.py.
     */
    return a + b;
}

// Example usage
const num1 = 5;
const num2 = 10;
const result = calculateSum(num1, num2);
console.log(`The sum of ${num1} and ${num2} is: ${result}`);